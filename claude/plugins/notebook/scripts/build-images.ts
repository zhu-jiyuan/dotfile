// Renders the critter SVGs to PNG for the terminal, which draws pictures but not SVG.
// Run: cd scripts && npm i && npx tsx build-images.ts
import { writeFileSync } from 'node:fs'
import { Resvg } from '@resvg/resvg-js'
import { MASCOTS, avatar, type Critter } from '../hooks/critters.ts'

const png = (svg: string, width: number) =>
  Buffer.from(new Resvg(svg, { fitTo: { mode: 'width', value: width } }).render().asPng()).toString('base64')

const critters: Critter[] = ['inky', 'sunny', 'pip', 'kero', 'miso', 'dot']
const avatars = Object.fromEntries(critters.map(who => [who, png(avatar(who), 64)]))
const mascots = Object.fromEntries(MASCOTS.map(m => [m.name, png(m.art, 300)]))

writeFileSync(
  new URL('../hooks/images.ts', import.meta.url),
  `// Generated by scripts/build-images.ts.\n` +
    `export const AVATAR_PNG: Record<string, string> = ${JSON.stringify(avatars)}\n` +
    `export const MASCOT_PNG: Record<string, string> = ${JSON.stringify(mascots)}\n`,
)
